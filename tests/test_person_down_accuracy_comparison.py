import json
from pathlib import Path
import unittest
from unittest.mock import patch

from analytics_lab import person_down_accuracy_comparison as accuracy
from analytics_lab import person_down_detector_comparison as shared
from analytics_lab import person_down_regression_evidence as regression
from analytics_lab import validation_seed as seed
from analytics_lab.evaluation import EvaluationSample, aggregate_person_down_evaluations, evaluate_person_down_candidates
from analytics_lab.validation import ModelArtifactIdentity, ValidationSampleRun, ValidationSuiteResult
from tests import test_person_down_detector_comparison as fixtures


class PersonDownAccuracyComparisonTests(unittest.TestCase):
    def setUp(self):
        # Composition reuses generated bytes only, without inheriting/discovering
        # the detector-comparison TestCase's unrelated test methods here.
        self.fixture = fixtures.PersonDownDetectorComparisonTests()
        self.fixture.setUp()
        self.addCleanup(self.fixture.doCleanups)
        self.root = self.fixture.root
        self.models = self.fixture.candidate_models
        self.specs = self.fixture.specs
        self.tables = self.fixture.tables
        self.versions = self.fixture.versions
        self.requests = self.fixture.requests
        allowed = {spec.source_url for spec in (*self.specs, *self.models)}
        self.fixture.payloads = {url: value for url, value in self.fixture.payloads.items()
                                 if url in allowed or url.endswith(".csv")}
        self.directories = []

    def _suite(self, samples, *, pipeline_config, evaluation_config,
               positive_events=None, negative_events=None, negative_duration=4970, **kwargs):
        candidate = pipeline_config.orientation_recovery
        positive_events = ((fixtures._event(1700, 4700),) if candidate else ()) if positive_events is None else positive_events
        negative_events = ((fixtures._event(0, 3000),) if candidate else ()) if negative_events is None else negative_events
        runs, evaluations = [], []
        for index, sample in enumerate(samples):
            duration = 6217 if index == 0 else negative_duration
            evaluation = evaluate_person_down_candidates(
                positive_events if index == 0 else negative_events, sample.labels,
                video_start_timestamp_ms=0, video_end_timestamp_ms=duration, config=evaluation_config,
            )
            frames = (187, 150)[index]
            observations = ((19, 29) if candidate else (11, 13))[index]
            runs.append(ValidationSampleRun(
                sample.sample_id, sample.site_id, sample.camera_id, sample.authorization_ref,
                sample.media_sha256, self.versions["openvino"], "CPU", frames, observations,
                10.0, frames * 100.0, evaluation,
            ))
            evaluations.append(EvaluationSample(sample.sample_id, sample.site_id, sample.camera_id, 0, duration, evaluation))
        models = tuple(ModelArtifactIdentity(spec.component, spec.relative_path, spec.size_bytes, spec.sha384, spec.license_id)
                       for spec in self.models)
        return ValidationSuiteResult(self.versions["openvino"], "CPU", models, tuple(runs),
                                     aggregate_person_down_evaluations(evaluations), 20.0, 337, 16850.0)

    def _context(self, *, suite=None, change=None):
        stack = ExitStack()
        stack.enter_context(patch.dict(shared.os.environ, self.fixture.environment, clear=True))
        stack.enter_context(patch.object(shared.platform, "system", return_value="Linux"))
        stack.enter_context(patch.object(accuracy, "_runtime_versions", return_value=self.versions))
        stack.enter_context(patch.object(accuracy, "_cpu_metadata", return_value={"performance_claim": False, "linux_cpu_model_name": "generated CPU metadata"}))
        for module in (shared, regression, seed):
            stack.enter_context(patch.object(module, "GMDCSA24_HELDOUT_S4", self.specs))
        for module in (shared, regression):
            stack.enter_context(patch.object(module, "_TABLES", self.tables))
        stack.enter_context(patch.object(accuracy, "OPENVINO_OMZ_PERSON_0200_FP16", self.models))

        def selected_models(model):
            self.assertEqual(model, "person-detection-0200")
            return self.models
        self.profile_call = stack.enter_context(patch.object(seed, "omz_artifacts_for_detector", side_effect=selected_models))
        original_prepare = seed.prepare_seed

        def prepare(directory, **kwargs):
            self.directories.append(Path(directory))
            manifest = original_prepare(directory, **kwargs)
            if change is not None:
                document = json.loads(manifest.read_text(encoding="utf-8"))
                change(document, manifest.parent)
                manifest.write_text(json.dumps(document), encoding="utf-8")
            return manifest
        self.prepare_call = stack.enter_context(patch.object(accuracy, "prepare_seed", side_effect=prepare))
        self.suite_call = stack.enter_context(patch.object(accuracy, "run_validation_suite", side_effect=suite or self._suite))
        stack.enter_context(redirect_stderr(io.StringIO()))
        return stack

    def _run(self, *, suite=None, change=None, opener=None):
        with self._context(suite=suite, change=change):
            return accuracy.run_comparison(self.root, opener=opener or self.fixture._opener)

    def _assert_clean(self):
        self.assertTrue(self.root.is_dir())
        self.assertEqual(list(self.root.iterdir()), [])
        self.assertTrue(all(not directory.exists() for directory in self.directories))

    def test_real_plan_has_only_0200_pose_and_one_frozen_flag_difference(self):
        plan = accuracy.comparison_plan()
        self.assertEqual(plan["max_media_bytes"], 7_996_782)
        self.assertEqual(plan["max_unique_model_bytes"], 12_304_842)
        self.assertEqual(len(plan["unique_models"]), 4)
        self.assertEqual(plan["suite_order"], ["orientation_off", "orientation_on"])
        self.assertEqual(plan["max_detector_passes_per_frame"], 3)
        settings = plan["pipeline_configs"]
        self.assertEqual([setting.pop("orientation_recovery") for setting in settings], [False, True])
        self.assertEqual(settings[0], settings[1])
        self.assertEqual(settings[0]["openvino"]["detector_model"], "person-detection-0200")
        self.assertEqual(settings[0]["openvino"]["detection_threshold"], .50)
        self.assertEqual(settings[0]["temporal"]["min_confidence"], .7)
        self.assertEqual(settings[0]["temporal"]["max_unknown_gap_ms"], 0)
        self.assertEqual(settings[0]["video"]["max_frames"], 1000)
        self.assertFalse(plan["false_alert_gate_eligible"])
        self.assertFalse(plan["new_heldout_evidence"])

    def test_actual_generated_byte_acquisition_once_and_two_suites_only_differ_by_optin(self):
        report = self._run()
        self.prepare_call.assert_called_once()
        self.assertEqual(self.prepare_call.call_args.kwargs["subset"], "subject4-regression")
        self.assertEqual(self.prepare_call.call_args.kwargs["detector_model"], "person-detection-0200")
        self.profile_call.assert_called_once_with("person-detection-0200")
        self.assertEqual(len(self.requests), 8)  # Two tables, two clips and exactly four models.
        self.assertEqual(set(self.requests), set(self.fixture.payloads))
        self.assertEqual(len(set(self.requests)), len(self.requests))
        self.assertFalse(any("retail-0013" in url for url in self.requests))
        self.assertTrue(all(url.endswith(".csv") for url in self.requests[:2]))
        self.assertEqual(self.suite_call.call_count, 2)
        left, right = self.suite_call.call_args_list
        self.assertEqual(left.args, right.args)
        for field in ("artifact_root", "config", "evaluation_config"):
            self.assertEqual(left.kwargs[field], right.kwargs[field])
        configs = [asdict(call.kwargs["pipeline_config"]) for call in (left, right)]
        self.assertEqual([cfg.pop("orientation_recovery") for cfg in configs], [False, True])
        self.assertEqual(configs[0], configs[1])
        self.assertTrue(report["temporary_assets_removed"])
        self.assertEqual(report["plan_sha256"], hashlib.sha256(regression._canonical(report["plan"])).hexdigest())
        for arm in ("baseline", "candidate"):
            recorded = report[arm]["activity_proxy_validation"]["model_artifacts"]
            self.assertEqual([item["relative_path"] for item in recorded], [spec.relative_path for spec in self.models])
        serialized = json.dumps(report, allow_nan=False)
        self.assertNotIn(str(self.root), serialized)
        self.assertNotIn("generated media metadata:", serialized)
        self._assert_clean()

    def test_recovered_positive_and_new_negative_event_are_both_retained(self):
        report = self._run()
        self.assertEqual(report["baseline"]["fall_activity_candidate_misses"], 1)
        self.assertEqual(report["candidate"]["fall_activity_candidate_matches"], 1)
        self.assertEqual(report["candidate"]["normal_clip_candidate_events"], 1)
        self.assertEqual(report["aggregate_deltas"], {
            "observations_processed": 24, "candidate_events": 2, "matched_events": 1, "missed_episodes": -1,
        })
        self.assertEqual(report["sample_deltas"][0]["matched_events"], 1)
        self.assertEqual(report["sample_deltas"][1]["candidate_events"], 1)
        self.assertFalse(report["false_alert_gate_eligible"])
        self.assertFalse(report["production_promoted"])
        self.assertFalse(report["commercial_accuracy_claim"])
        self.assertIsNone(report["clinical_false_positive_delta"])

    def test_silent_arms_keep_both_misses_without_success_or_promotion(self):
        report = self._run(suite=lambda *args, **kwargs: self._suite(*args, positive_events=(), negative_events=(), **kwargs))
        for arm in ("baseline", "candidate"):
            self.assertEqual(report[arm]["fall_activity_candidate_misses"], 1)
            self.assertEqual(report[arm]["fall_activity_candidate_matches"], 0)
            self.assertEqual(report[arm]["normal_clip_candidate_events"], 0)
        self.assertFalse(report["zero_candidates_is_success"])
        self.assertFalse(report["production_promoted"])

    def test_tail_never_supplies_scored_negative_exposure_or_delta(self):
        for duration in (4000, 4001, 4970):
            with self.subTest(duration=duration):
                report = self._run(suite=lambda *args, **kwargs: self._suite(*args, negative_duration=duration, **kwargs))
                candidate = report["candidate"]
                self.assertEqual(candidate["normal_clip_candidate_events"], 1)
                self.assertEqual(candidate["normal_clip_decoded_exposure_ms"], duration)
                self.assertFalse(candidate["false_alert_gate_eligible"])
                self.assertIsNone(candidate["clinical_false_positives"])
                if duration > 4000:
                    self.assertEqual(candidate["normal_clip_unannotated_tail_ms"], duration - 4000)
                    for field in ("normal_clip_scored_activity_false_alerts", "normal_clip_scored_activity_camera_hours",
                                  "normal_clip_scored_activity_false_alerts_per_camera_hour"):
                        self.assertIsNone(candidate[field])
                    self.assertIsNone(report["normal_clip_scored_activity_false_alerts_delta"])
                else:
                    self.assertEqual(candidate["normal_clip_scored_activity_false_alerts"], 1)
                    self.assertEqual(report["normal_clip_scored_activity_false_alerts_delta"], 1)
                self._assert_clean()

    def test_wrong_annotation_and_corrupt_model_fail_before_any_suite(self):
        for phase in ("annotation", "model"):
            def opener(request, timeout):
                if phase == "annotation" and request.full_url.endswith("Fall.csv"):
                    return io.BytesIO(b"generated corrupt table")
                if phase == "model" and "/person-detection-0200/" in request.full_url:
                    payload = self.fixture.payloads[request.full_url].replace(b"generated", b"invented ", 1)
                    return io.BytesIO(payload)
                return self.fixture._opener(request, timeout)
            with self.subTest(phase=phase), self.assertRaises((RuntimeError, ValueError)):
                self._run(opener=opener)
            self.suite_call.assert_not_called()
            self.assertEqual(self.prepare_call.call_count, 0 if phase == "annotation" else 1)
            self._assert_clean()

    def test_source_and_original_label_changes_reject_before_either_suite(self):
        changes = (
            lambda doc, _: doc["samples"][0].update(media_sha256="0" * 64),
            lambda doc, _: doc["samples"][0].update(authorization_ref="different-rights"),
            lambda doc, _: doc["samples"][0]["labels"][0].update(end_timestamp_ms=5999),
            lambda doc, _: doc["samples"].reverse(),
            lambda doc, _: doc["config"].update(max_samples=3),
        )
        for index, change in enumerate(changes):
            with self.subTest(change=index), self.assertRaises((RuntimeError, ValueError)):
                self._run(change=change)
            self.suite_call.assert_not_called()
            self._assert_clean()

    def test_result_identity_drift_in_either_arm_rejects_without_delta(self):
        changes = (
            lambda result: replace(result, runtime_version="other"),
            lambda result: replace(result, model_artifacts=tuple(reversed(result.model_artifacts))),
            lambda result: replace(result, sample_runs=tuple(reversed(result.sample_runs))),
        )
        for bad_mode in (False, True):
            for index, change in enumerate(changes):
                def suite(*args, **kwargs):
                    result = self._suite(*args, **kwargs)
                    return change(result) if kwargs["pipeline_config"].orientation_recovery == bad_mode else result
                with self.subTest(mode=bad_mode, change=index), self.assertRaises(RuntimeError):
                    self._run(suite=suite)
                self.assertEqual(self.suite_call.call_count, 2 if bad_mode else 1)
                self._assert_clean()

    def test_exposure_drift_and_uncovered_positive_reject(self):
        def changed_exposure(*args, **kwargs):
            return self._suite(*args, negative_duration=4971 if kwargs["pipeline_config"].orientation_recovery else 4970, **kwargs)
        with self.assertRaisesRegex(RuntimeError, "decoded exposure differs"):
            self._run(suite=changed_exposure)
        self._assert_clean()

        def uncovered(*args, **kwargs):
            result = self._suite(*args, **kwargs)
            first = result.sample_runs[0]
            return replace(result, sample_runs=(replace(first, evaluation=replace(first.evaluation, duration_ms=5999)), result.sample_runs[1]))
        with self.assertRaisesRegex(RuntimeError, "positive label exceeds decoded coverage"):
            self._run(suite=uncovered)
        self.assertEqual(self.suite_call.call_count, 1)
        self._assert_clean()

    def test_acquisition_and_each_suite_failure_cleanup_without_retry(self):
        for phase in ("acquisition", False, True):
            def opener(request, timeout):
                if phase == "acquisition" and "/person-detection-0200/" in request.full_url:
                    raise RuntimeError("generated asset failure")
                return self.fixture._opener(request, timeout)
            def suite(*args, **kwargs):
                if kwargs["pipeline_config"].orientation_recovery == phase:
                    raise RuntimeError("generated suite failure")
                return self._suite(*args, **kwargs)
            with self.subTest(phase=phase), self.assertRaises(RuntimeError):
                self._run(suite=suite, opener=opener)
            self.prepare_call.assert_called_once()
            self.assertEqual(self.suite_call.call_count, 0 if phase == "acquisition" else (2 if phase else 1))
            self._assert_clean()

    def test_cli_outputs_one_document_after_cleanup_with_no_network(self):
        output = io.StringIO()
        with self._context(), redirect_stdout(output), patch.object(accuracy.urllib.request, "urlopen", side_effect=AssertionError("no network")):
            original = accuracy.run_comparison
            with patch.object(accuracy, "run_comparison", side_effect=lambda path: original(path, opener=self.fixture._opener)):
                self.assertEqual(accuracy.main(["--work-dir", str(self.root)]), 0)
        report = json.loads(output.getvalue())
        self.assertTrue(report["temporary_assets_removed"])
        self.assertFalse(report["production_promoted"])
        self._assert_clean()


